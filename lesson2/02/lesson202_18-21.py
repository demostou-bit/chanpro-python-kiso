# strクラスのインスタンスを生成し変数helloに代入
hello1 = "Hello Python1"
print(hello1)

# strコンストラクタでインスタンスを生成
hello2 = str("Hello Python2")
print(hello2)

# str関数で数値を文字列に変換
year = str(2026)
print(year)

# intコンストラクタとfloatコンストラクタ
age = int("34") # 文字列を整数に変換
pi = float("3.14") # 文字列を浮動小数点数に変換

print(age)
print(pi)